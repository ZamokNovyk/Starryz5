-- 4. TABLA 'users_daily_stats' (Histórico diario de estadísticas de usuarios)
CREATE TABLE IF NOT EXISTS public.users_daily_stats (
  id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  target_user_id TEXT NOT NULL,
  date DATE NOT NULL,
  knows_count INTEGER NOT NULL DEFAULT 0,
