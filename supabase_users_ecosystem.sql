-- 1. TABLA 'users_votes' (Calificaciones de 1 a 5 estrellas para perfiles de usuario)
CREATE TABLE IF NOT EXISTS public.users_votes (
  id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
  target_user_id TEXT NOT NULL,       -- ID del usuario que recibe el voto
  user_uid TEXT NOT NULL,             -- ID del usuario que vota
  stars SMALLINT NOT NULL CHECK (stars >= 1 AND stars <= 5),
  created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_users_votes_target ON public.users_votes(target_user_id);
CREATE INDEX IF NOT EXISTS idx_users_votes_voter ON public.users_votes(user_uid, target_user_id);

ALTER TABLE public.users_votes ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Lectura pública de users_votes" ON public.users_votes;
CREATE POLICY "Lectura pública de users_votes"
  ON public.users_votes FOR SELECT
  USING (true);

DROP POLICY IF EXISTS "Inserción de users_votes" ON public.users_votes;
CREATE POLICY "Inserción de users_votes"
  ON public.users_votes FOR INSERT
  WITH CHECK (true);

DROP POLICY IF EXISTS "Eliminación de users_votes" ON public.users_votes;
CREATE POLICY "Eliminación de users_votes"
  ON public.users_votes FOR DELETE
  USING (true);


